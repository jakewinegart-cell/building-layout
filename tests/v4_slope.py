"""v4 variable slope: roof card slider + number box (0.5:12–12:12, 0.25 steps), shed high/low walls back-calculate pitch,
house roof pitch + eave (ASSUMED 4:12 / 7.9 ft) editable, live Plan/3D, IRC warnings, Price check marked out of date, wizard slope phrases.
    python3 tests/v4_slope.py [base_url]"""
import sys, os, json
from playwright.sync_api import sync_playwright
BASE = sys.argv[1] if len(sys.argv) > 1 else 'http://127.0.0.1:8850/'
SH = 'screenshots/v4/'; os.makedirs(SH, exist_ok=True)
results = []
def check(name, ok, detail=''):
    results.append((name, bool(ok), detail)); print(('PASS ' if ok else 'FAIL ') + name + (('  — ' + str(detail)) if detail else ''))
M = 'window.__layout.getModel()'
def roofp(pg): return pg.evaluate(f"(() => {{ const p = {M}.layers.find(l => l.id === 'roof').params; return {{ shape: p.shape, pitch: p.pitch, shed: p.shed, cov: p.roofing && p.roofing.covering }}; }})()")
def roofsig(pg): return pg.evaluate(f"JSON.stringify({M}.layers.find(l => l.id === 'roof').objects.map(o => [o.geometry, o.z, o.height]))")
def hist(pg): return pg.evaluate("window.__layout.history().undo.length")
def fresh(pg):
    pg.goto(BASE); pg.wait_for_timeout(300); pg.evaluate("() => { localStorage.clear(); sessionStorage.clear(); }")
    pg.evaluate("""async () => { const m = await (await fetch('content-v4/reference/example-20x16.model.json', {cache:'no-store'})).json(); localStorage.setItem('buildingLayout.model.v1', JSON.stringify(m)); }""")
    pg.reload(); pg.wait_for_timeout(1200)
    try: pg.wait_for_selector('#zipModal #zmSkip', timeout=2500); pg.click('#zipModal #zmSkip'); pg.wait_for_timeout(250)
    except Exception: pass
def roof_card(pg):
    pg.click('.tabs [data-tab="layers"]'); pg.wait_for_timeout(150); pg.click('.lrow[data-layer="roof"] .name'); pg.wait_for_timeout(150)
    pg.click('.tabs [data-tab="props"]'); pg.wait_for_timeout(250)
def slide(pg, v, commit=True):
    pg.evaluate(f"(() => {{ const s = document.querySelector('#pitchSlider'); s.value = {v}; s.dispatchEvent(new Event('input', {{bubbles:true}})); {'s.dispatchEvent(new Event(\"change\", {bubbles:true}));' if commit else ''} }})()")
    pg.wait_for_timeout(350)
def chk_ids(pg): return pg.evaluate("[...document.querySelectorAll('#slopeChecks .slChk')].map(e => (e.dataset.id || e.id) + ':' + e.className)")
def setnum(pg, sel, v): pg.fill(sel, str(v)); pg.press(sel, 'Tab'); pg.wait_for_timeout(400)

with sync_playwright() as p:
    b = p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'])
    pg = b.new_page(viewport={'width': 1280, 'height': 860}); errs = []
    pg.on('pageerror', lambda e: errs.append(str(e))); pg.on('console', lambda m: errs.append(m.text) if m.type == 'error' and 'Failed to load resource' not in m.text else None)
    pg.on('dialog', lambda d: d.accept())
    fresh(pg); roof_card(pg)
    a = pg.evaluate("(() => { const s = document.querySelector('#pitchSlider'), n = document.querySelector('#pitchNum'); return s && n ? [s.min, s.max, s.step, n.min, n.max, n.step, s.value] : null; })()")
    check('roof card has a slope slider + number box, 0.5–12 in 0.25 steps', a and a[:6] == ['0.5', '12', '0.25', '0.5', '12', '0.25'], a)
    check('no "Shed (later)" left; shed is a real choice', 'Shed (later)' not in pg.inner_text('#layerCard') and pg.locator('#layerCard select[data-k="shape"] option[value="shed"]').count() == 1)
    s0 = roofsig(pg); h0 = hist(pg)
    slide(pg, 6.25, commit=False)
    check('dragging the slider updates the roof live (Plan/3D) before release', roofp(pg)['pitch'] == 6.25 and roofsig(pg) != s0 and pg.input_value('#pitchNum') == '6.25', roofp(pg)['pitch'])
    check('readout shows 6.25:12 and degrees', '6.25:12' in pg.inner_text('#slopeRead') and '°' in pg.inner_text('#slopeRead'), pg.inner_text('#slopeRead'))
    check('live drag does not add an undo step; release does', hist(pg) == h0 and (slide(pg, 6.25) or True) and hist(pg) == h0 + 1, (h0, hist(pg)))
    setnum(pg, '#pitchNum', 3.1)
    check('number box snaps to 0.25 and syncs the slider (3.1 → 3)', roofp(pg)['pitch'] == 3 and pg.input_value('#pitchSlider') == '3', roofp(pg)['pitch'])
    setnum(pg, '#pitchNum', 20); check('number box clamps to 12:12', roofp(pg)['pitch'] == 12)
    setnum(pg, '#pitchNum', 0.1); check('number box clamps to 0.5:12', roofp(pg)['pitch'] == 0.5)
    ids = chk_ids(pg)
    check('0.5:12 with shingles → V-ROOF-01 block shown (2:12 minimum)', any(i.startswith('V-ROOF-01') and 'block' in i for i in ids), ids)
    slide(pg, 3); ids = chk_ids(pg)
    check('3:12 → double underlayment warning (V-ROOF-02), no block', any(i.startswith('V-ROOF-02') and 'warn' in i for i in ids) and not any('block' in i for i in ids), ids)
    slide(pg, 5); ids = chk_ids(pg)
    check('5:12 → no shingle slope warnings', not any(i.startswith(('V-ROOF-01', 'V-ROOF-02')) for i in ids), ids)
    # ---- shed: high/low walls back-calculate the pitch, pitch moves the high wall
    pg.select_option('#layerCard select[data-k="shape"]', 'shed'); pg.wait_for_timeout(500)
    check('shed shows high-wall side + high/low height inputs', all(pg.locator(s).count() for s in ['#shedHighSide', '#shedHi', '#shedLo']))
    pg.select_option('#shedHighSide', 'S'); pg.wait_for_timeout(400)
    setnum(pg, '#shedLo', 8); setnum(pg, '#shedHi', 12)
    r = roofp(pg); run = pg.evaluate(f"(() => {{ const p = {M}.layers.find(l => l.id === 'roof').params; return 12 * (p.shed.highPlateFt - p.shed.lowPlateFt) / p.pitch; }})()")
    check('high 12 / low 8 over a 16 ft run back-calculates 3:12', r['shed']['highPlateFt'] == 12 and r['shed']['lowPlateFt'] == 8 and 2 < r['pitch'] < 4 and abs(run - 16) < 0.05 and r['pitch'] == 3, (r['pitch'], run))
    check('slider + number box follow the heights', abs(float(pg.input_value('#pitchNum')) - round(r['pitch'] * 4) / 4) < 0.26 and pg.input_value('#pitchNum') == pg.input_value('#pitchSlider'), pg.input_value('#pitchNum'))
    slide(pg, 4); r = roofp(pg)
    check('slider 4:12 on a shed keeps the low wall and moves the high wall', r['shed']['lowPlateFt'] == 8 and abs(r['shed']['highPlateFt'] - (8 + 4 * run / 12)) < 0.05 and abs(r['pitch'] - 4) < 0.01, r['shed'])
    check('high-wall input shows the new height', abs(float(pg.input_value('#shedHi')) - r['shed']['highPlateFt']) < 0.01, pg.input_value('#shedHi'))
    wh = pg.evaluate(f"(() => {M}.layers.find(l => l.id === 'walls').objects.filter(o => o.props.exterior).map(o => [o.props.plateHeightFt, o.props.plateHeightEndFt]))()")
    check('walls follow: high wall ≈ high height, low wall = 8 ft', any(abs(x[0] - r['shed']['highPlateFt']) < 0.01 for x in wh) and any(x[0] == 8 and x[1] == 8 for x in wh), wh)
    pg.screenshot(path=SH + '40-slope-slider.png')
    # ---- house: assumed pitch/eave, editable, RF-TIE-01
    pg.select_option('#attachSide', 'S'); pg.wait_for_timeout(500)
    card = pg.inner_text('#layerCard')
    check('attach to house adds the house + its roof pitch / eave inputs labelled "assumed"', pg.locator('#housePitch').count() and pg.locator('#houseEave').count() and card.lower().count('assumed') >= 2, card[-300:])
    check('house defaults: 4:12 and 7.9 ft', pg.input_value('#housePitch') == '4' and pg.input_value('#houseEave') == '7.9', (pg.input_value('#housePitch'), pg.input_value('#houseEave')))
    ids = chk_ids(pg)
    check('shed against the house at 12 ft high runs the eave-clearance check (RF-TIE-01)', any(i.startswith('RF-TIE-01') for i in ids), ids)
    setnum(pg, '#houseEave', 14); setnum(pg, '#housePitch', 6)
    H = pg.evaluate(f"(() => {M}.layers.find(l => l.id === 'site').objects.find(o => o.props.existingRoof).props.existingRoof)()")
    check('editing house pitch / eave stores them as entered (no longer assumed)', H.get('pitch') == 6 and H.get('eaveUndersideFt') == 14 and not H['assumed']['pitch'] and not H['assumed']['eaveUndersideFt'], H)
    check('label flips from "assumed" to "entered"', 'entered' in pg.inner_text('#layerCard'))
    # ---- price check marked out of date after a slope change
    fresh(pg)
    pg.evaluate("() => { const m = window.__layout.getModel(); }")
    pg.click('#doneBtn'); pg.wait_for_selector('#pcRun', timeout=15000)
    if pg.locator('.pc-skip[data-skip="beam"]').count(): pg.click('.pc-skip[data-skip="beam"]')
    for i in [e.get_attribute('data-complete') for e in pg.locator('#pcLayers input[data-complete]:not(:checked)').all()]: pg.check(f'#pcLayers input[data-complete="{i}"]'); pg.wait_for_timeout(50)
    pg.click('#pcRun'); pg.wait_for_selector('#rpTotal', timeout=20000); pg.click('#rpClose'); pg.wait_for_timeout(300)
    roof_card(pg)
    check('fresh Price check → no out-of-date note', pg.locator('#slopeStale').count() == 0)
    slide(pg, 7)
    check('slope change → "Price check is out of date" in the roof card', pg.locator('#slopeStale').count() == 1 and 'out of date' in pg.inner_text('#slopeStale'))
    st = pg.evaluate("(() => { const r = document.querySelector('.lrow[data-layer=\"roof\"]'); return r ? r.innerText + ' ' + r.className : ''; })()")
    pg.click('.tabs [data-tab="layers"]'); pg.wait_for_timeout(200)
    st = pg.evaluate("(() => { const r = document.querySelector('.lrow[data-layer=\"roof\"]'); return r ? r.innerHTML : ''; })()")
    check('Layers list marks the roof price stale', 'stale' in st.lower() or 'out of date' in st.lower(), st[:200])
    # ---- wizard slope phrases (local, no AI)
    pg.route('**/workers.dev/**', lambda rt: rt.abort())
    pg.click('#wizardBtn'); pg.wait_for_timeout(250)
    def say(t): pg.fill('#wzInput', t); pg.press('#wzInput', 'Enter'); pg.wait_for_timeout(900)
    def pv(): return pg.evaluate(f"window.__layout.app.getModel().layers.find(l => l.id === 'roof').params.pitch")
    for phrase, want in [('slope 6', 6), ('make the slope 3:12', 3), ('lowest slope for shingles', 2), ('steeper', None)]:
        before = pg.evaluate("window.__layout.getModel().layers.find(l => l.id === 'roof').params.pitch")
        say(phrase); got = pv(); ok = pg.locator('#wzPreview').count() == 1 and (got == want if want is not None else got == before + 1)
        check(f'wizard "{phrase}" previews pitch {want if want is not None else before + 1}', ok, got)
        if pg.locator('#wzApply:not([disabled])').count(): pg.click('#wzApply'); pg.wait_for_timeout(400)
        else: pg.click('#wzCancel'); pg.wait_for_timeout(300)
    say('house roof is 5/12')
    check('wizard "house roof is 5/12" without a house asks to attach first', 'Built against the house' in pg.inner_text('#wzLog'))
    check('no page errors', not errs, errs[:3])
    b.close()
n = sum(1 for r in results if r[1]); print(f'\n{n}/{len(results)} passed'); sys.exit(0 if n == len(results) else 1)
